"""
Generated by claude code

Estimate the number of lines of C++ code in the repository.

Counts all git-tracked C++ source and header files, grouped by top level
directory. For each directory it reports:

  raw         - total lines
  code        - lines that are not blank and not only comments
  trivial     - code lines that are only braces, access specifiers,
                #include or include guards
  substantive - code minus trivial

Usage (from anywhere inside the repository):

  python utils/countlines.py
"""
import collections
import os
import re
import subprocess

_extensions = re.compile(r'\.(cc|cpp|cxx|hh|h|hpp|icc|C)$')
# string literals are matched so comment markers inside them are ignored
_commentsAndStrings = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\\n])*"', flags=re.S)
_trivialLines = {'{', '}', '};', '{}', 'public:', 'private:', 'protected:'}


def _StripComments(text):
    def Replace(match):
        s = match.group(0)
        if s.startswith('"'):
            return s
        return '\n' * s.count('\n') # keep line structure
    return _commentsAndStrings.sub(Replace, text)


def _IsTrivial(line):
    if line in _trivialLines:
        return True
    if line.startswith(('#include', '#endif', '#ifndef')):
        return True
    if line.startswith('#define') and len(line.split()) == 2:
        return True
    return False


def CountLines(repoDir='.'):
    """
    Return dicts of raw, code and trivial line counts keyed by top level directory.
    """
    root = subprocess.run(['git', '-C', repoDir, 'rev-parse', '--show-toplevel'],
                          capture_output=True, text=True, check=True).stdout.strip()
    files = subprocess.run(['git', '-C', root, 'ls-files'],
                           capture_output=True, text=True, check=True).stdout.split()

    raw     = collections.Counter()
    code    = collections.Counter()
    trivial = collections.Counter()
    for f in files:
        if not _extensions.search(f):
            continue
        d = f.split('/')[0]
        try:
            with open(os.path.join(root, f), errors='ignore') as fh:
                text = fh.read()
        except OSError:
            continue
        raw[d] += text.count('\n')
        for line in _StripComments(text).split('\n'):
            line = line.strip()
            if not line:
                continue
            code[d] += 1
            if _IsTrivial(line):
                trivial[d] += 1
    return raw, code, trivial


def Print(repoDir='.'):
    raw, code, trivial = CountLines(repoDir)
    print(f"{'directory':14s} {'raw':>8s} {'code':>8s} {'trivial':>8s} {'substantive':>12s}")
    for d in sorted(code, key=lambda k: -code[k]):
        print(f"{d:14s} {raw[d]:8d} {code[d]:8d} {trivial[d]:8d} {code[d]-trivial[d]:12d}")
    tRaw, tCode, tTrivial = sum(raw.values()), sum(code.values()), sum(trivial.values())
    print(f"{'TOTAL':14s} {tRaw:8d} {tCode:8d} {tTrivial:8d} {tCode-tTrivial:12d}")


if __name__ == '__main__':
    Print()
