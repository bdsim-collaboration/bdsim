"""
Generated by claude code.
Print a table of C++ line counts per top level directory comparing cloc
with the counts from countlines.py.

Requires cloc to be installed and the tabulate python package.

Usage (from anywhere inside the repository):

  python utils/linecounttable.py
  python utils/linecounttable.py --format github
"""
import argparse
import collections
import csv
import os
import shutil
import subprocess
import sys

from tabulate import tabulate

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import countlines

_clocLanguages = "C++,C/C++ Header,C"


def _RepoRoot(repoDir='.'):
    return subprocess.run(['git', '-C', repoDir, 'rev-parse', '--show-toplevel'],
                          capture_output=True, text=True, check=True).stdout.strip()


def ClocCounts(root):
    """
    Return dicts of blank, comment and code line counts from cloc keyed by top level directory.
    """
    if shutil.which('cloc') is None:
        raise RuntimeError("cloc not found - please install it (e.g. brew install cloc)")
    result = subprocess.run(['cloc', '--vcs=git', '--include-lang=' + _clocLanguages,
                             '--quiet', '--by-file', '--csv', '.'],
                            cwd=root, capture_output=True, text=True, check=True)
    blank   = collections.Counter()
    comment = collections.Counter()
    code    = collections.Counter()
    for row in csv.reader(result.stdout.splitlines()):
        if len(row) < 5 or row[0] in ('language', 'SUM'):
            continue
        path = os.path.normpath(row[1])
        d = path.split(os.sep)[0]
        blank[d]   += int(row[2])
        comment[d] += int(row[3])
        code[d]    += int(row[4])
    return blank, comment, code


def Table(repoDir='.', tablefmt='simple'):
    root = _RepoRoot(repoDir)
    blank, comment, clocCode = ClocCounts(root)
    _, scriptCode, trivial = countlines.CountLines(root)

    dirs = sorted(set(clocCode) | set(scriptCode),
                  key=lambda d: -(blank[d] + comment[d] + clocCode[d]))
    rows = []
    for d in dirs:
        raw = blank[d] + comment[d] + clocCode[d]
        rows.append([d, raw, blank[d], comment[d], clocCode[d],
                     scriptCode[d], scriptCode[d] - trivial[d]])
    totals = [sum(col) for col in zip(*[r[1:] for r in rows])]
    rows.append(['TOTAL'] + totals)

    headers = ['Directory', 'Raw', 'Blank', 'Comment', 'Code (cloc)',
               'Code (script)', 'Code (script, substantive)']
    return tabulate(rows, headers=headers, tablefmt=tablefmt, intfmt=',')


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('-f', '--format', default='simple',
                        help="tabulate table format, e.g. simple, github, rst, latex")
    args = parser.parse_args()
    print(Table(tablefmt=args.format))


if __name__ == '__main__':
    main()
